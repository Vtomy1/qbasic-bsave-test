import JSZip from 'jszip';
import { ScreenModeConfig, RGBColor } from '../types/bsave';
import { BSAVEExportResult } from './bsaveEncoder';
import { GeneratedCode } from './codeGenerator';

export async function createDosboxZipBundle(
  baseName: string,
  exportResult: BSAVEExportResult,
  generatedCode: GeneratedCode,
  mode: ScreenModeConfig,
  palette: RGBColor[]
): Promise<Blob> {
  const zip = new JSZip();
  const cleanName = baseName.replace(/[^a-zA-Z0-9_-]/g, '_').toUpperCase();

  const bsvName = `${cleanName}.BSV`;
  const basName = `${cleanName}.BAS`;
  const palName = `${cleanName}.PAL`;
  const binName = `${cleanName}.BIN`;

  // Add BSAVE binary with 7-byte header
  zip.file(bsvName, exportResult.bsaveBuffer);

  // Add Raw binary memory dump (no header)
  zip.file(binName, exportResult.rawMemoryBuffer);

  // Add QBasic runnable source code
  zip.file(basName, generatedCode.sourceCode);

  // Add VGA DAC Palette (768 bytes) if 256 or 16 colors
  if (mode.bitDepth === 8 || mode.bitDepth === 4) {
    zip.file(palName, exportResult.palBuffer);
  }

  // Create README.TXT with authentic MS-DOS documentation
  const readme = `================================================================================
MS-DOS QBASIC / QUICKBASIC BSAVE GRAPHIC PACKAGE
Image:        ${cleanName}
Screen Mode:  ${mode.name} (${mode.width}x${mode.height}, ${mode.bitDepth}-bit, ${mode.colorsCount} colors)
Memory Seg:   ${exportResult.headerInfo.segmentHex}
Offset:       ${exportResult.headerInfo.offsetHex}
Payload Size: ${exportResult.headerInfo.lengthBytes} bytes
Date:         ${new Date().toUTCString()}
================================================================================

PACKAGE CONTENTS:
1. ${bsvName}  - Native MS-DOS BSAVE binary file with standard 7-byte header:
                Byte 0:    0xFD (BSAVE signature)
                Bytes 1-2: Segment address (${exportResult.headerInfo.segmentHex})
                Bytes 3-4: Offset address (${exportResult.headerInfo.offsetHex})
                Bytes 5-6: Data length (${exportResult.headerInfo.lengthBytes} bytes)
                Bytes 7+:  Pixel memory stream

2. ${basName}  - Ready-to-run QBasic / QuickBASIC 4.5 / QB64 source code loader.

3. ${binName}  - Raw memory payload without the 7-byte BSAVE header (for C, Assembly, or custom engines).

${mode.bitDepth === 8 ? `4. ${palName}  - Standard 768-byte VGA DAC palette file (256 * 3 bytes, 6-bit 0-63 RGB).\n` : ''}

HOW TO RUN IN DOSBOX:
---------------------
1. Copy all files into your DOSBox shared directory (e.g. C:\\DOS).
2. Launch DOSBox:
   MOUNT C C:\\DOS
   C:
3. Start QBasic or QuickBASIC:
   QBASIC /RUN ${basName}

HOW TO RUN IN QB64 (Windows / Mac / Linux):
------------------------------------------
1. Open QB64.
2. File -> Open -> Select '${basName}'.
3. Press F5 to compile and execute!

GENERATED BY: QBasic BSAVE Converter & Loader
================================================================================
`;
  zip.file('README.TXT', readme);

  return await zip.generateAsync({ type: 'blob' });
}
